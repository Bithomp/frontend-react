export const dappsApiUrl = (convertCurrency, period, includeDetails = false) => {
  let apiUrl = `v2/dapps?convertCurrencies=${encodeURIComponent(convertCurrency)}&previousPeriod=true&previousPeriodMode=calendar-1`
  if (period) apiUrl += `&period=${encodeURIComponent(period)}`
  if (includeDetails) apiUrl += '&dappDetails=true'
  return apiUrl
}

export const DAPP_CHART_PERIODS = ['week', 'month', 'year', 'all']
export const DAPP_CHART_SPANS = ['day', 'week', 'month']

export const dappChartSpan = (period) => {
  if (period === 'year') return 'week'
  if (period === 'all') return 'month'
  return 'day'
}

export const dappChartApiUrl = (sourceTag, convertCurrency, period = 'month', span) => {
  const normalizedPeriod = DAPP_CHART_PERIODS.includes(period) ? period : 'month'
  const normalizedSpan = DAPP_CHART_SPANS.includes(span) ? span : dappChartSpan(normalizedPeriod)
  const params = new URLSearchParams({
    period: normalizedPeriod,
    span: normalizedSpan
  })
  if (convertCurrency) params.set('convertCurrencies', String(convertCurrency).toLowerCase())
  return `v2/dapp/${encodeURIComponent(sourceTag)}/chart?${params.toString()}`
}

export const dappTransactionsApiUrl = (sourceTag, convertCurrency, options = {}) => {
  const { type = 'all', status = 'all', order = 'new', marker, limit = 20 } = options
  const params = new URLSearchParams({
    order,
    limit: String(limit),
    currencyDetails: 'true'
  })
  if (convertCurrency) params.set('convertCurrencies', String(convertCurrency).toLowerCase())
  if (type && type !== 'all') params.set('type', type)
  if (status && status !== 'all') params.set('status', status)
  if (marker) params.set('marker', typeof marker === 'object' ? JSON.stringify(marker) : marker)
  return `v2/dapp/${encodeURIComponent(sourceTag)}/transactions?${params.toString()}`
}

const normalizeWalletId = (w) => (typeof w === 'string' ? w.trim().toLowerCase() : '')

export const WALLET_FREQ = (() => {
  const metaObj = DAPPS_META?.[0] || {}
  const freq = {}

  Object.values(metaObj).forEach((entry) => {
    const list = [
      ...(Array.isArray(entry?.wallets) ? entry.wallets : []),
      ...(Array.isArray(entry?.walletconnect) ? entry.walletconnect : [])
    ]

    list
      .map(normalizeWalletId)
      .filter(Boolean)
      .forEach((id) => {
        freq[id] = (freq[id] || 0) + 1
      })
  })

  return freq
})()

export const WALLET_POPULARITY = (() => {
  // Most frequent first; tie-breaker: alphabetical
  return Object.entries(WALLET_FREQ)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([id]) => id)
})()

export const buildPrevMapBySourceTag = (prevList) => {
  if (!Array.isArray(prevList) || prevList.length === 0) return null
  const m = new Map()
  for (const d of prevList) {
    if (d?.sourceTag == null) continue
    m.set(String(d.sourceTag), d)
  }
  return m
}

const AGENT_SOURCE_TAG_START = Date.UTC(2026, 4, 30)
const SHORT_MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec']

export const generatedAgentNameBySourceTag = (sourceTag) => {
  const value = String(sourceTag ?? '')
  const match = value.match(/^(\d{2})(\d{2})(\d{2})(\d{4})$/)
  if (!match) return null

  const [, shortYear, monthText, dayText, agentText] = match
  const year = 2000 + Number(shortYear)
  const month = Number(monthText)
  const day = Number(dayText)
  const agent = Number(agentText)
  const date = Date.UTC(year, month - 1, day)
  const parsedDate = new Date(date)
  const now = new Date()
  const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate())

  if (
    date <= AGENT_SOURCE_TAG_START ||
    date > today ||
    parsedDate.getUTCFullYear() !== year ||
    parsedDate.getUTCMonth() !== month - 1 ||
    parsedDate.getUTCDate() !== day
  ) {
    return null
  }

  return `${SHORT_MONTHS[month - 1]} ${day}, Make Waves ${agent}`
}
